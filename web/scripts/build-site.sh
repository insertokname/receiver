#
# Assembles the static site in web/dist/site/ (deployed at /receiver/):
#   index.html app.js chunks/ sql/ stylesheets/ fonts/ images/ sounds/ locales/
#                               the web app: Desktop's renderer (web/dist/app, renderer/build.sh)
#   transport/                  the built transport (web/transport/dist); the app's copy of
#                               its WebAssembly is transport/webtor_wasm_bg.wasm
#   transport/tor/              Tor directory snapshot (consensus, authority certificates,
#                               microdescriptors; brotli), verified before it is shipped
#   SHA256SUMS, SOURCE          digest of every file except the Tor snapshot, and the
#                               commits it was built from (scripts/verify-site.sh)
#   lib/                        shared page code + protobuf code generated by protopiler
#   test/                       transport checks page (web/transport-test)
#   libsignal/                  libsignal checks page and libsignal's WebAssembly (web/libsignal)
#
# Usage: scripts/build-site.sh [--tor-dir DIR]
#   By default a fresh directory snapshot is fetched from the Tor directory
#   authorities (webtor-rs scripts/fetch-consensus.sh). --tor-dir reuses
#   DIR/consensus.txt.br, DIR/certs.txt.br and DIR/microdescriptors.txt.br
#   instead. Either way the snapshot must verify (transport/verify-directory.mjs)
#   or the build fails.
set -euo pipefail

WEB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="$(cd "$WEB/.." && pwd)"
SITE="$WEB/dist/site"
TOR_DIR=""

while [ $# -gt 0 ]; do
  case "$1" in
    --tor-dir) TOR_DIR="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [ ! -f "$WEB/transport/dist/pkg/webtor_wasm_bg.wasm" ]; then
  echo "transport not built: run web/transport/build.sh first" >&2
  exit 1
fi
if [ ! -f "$WEB/libsignal/dist/package/wasm/libsignal_node.wasm" ]; then
  echo "libsignal not built: run web/libsignal/build.sh first" >&2
  exit 1
fi
if [ ! -f "$WEB/dist/app/index.html" ]; then
  echo "web app not built: run web/renderer/build.sh first" >&2
  exit 1
fi
if [ ! -x "$WEB/node_modules/.bin/protopiler" ]; then
  echo "dependencies missing: run pnpm install in web/" >&2
  exit 1
fi

rm -rf "$SITE"
mkdir -p "$SITE/transport/tor" "$SITE/lib" "$SITE/test"

cp -r "$WEB/transport/dist/." "$SITE/transport/"
find "$SITE/transport" -name '*.d.ts' -delete
cp "$WEB/transport-test/index.html" "$WEB/transport-test/test.js" "$WEB/transport-test/wrong-ca.pem" "$SITE/test/"
cp "$WEB/lib/signal.js" "$SITE/lib/"
node "$WEB/libsignal/check/build.mjs" "$SITE/libsignal"
# The app at the site's root; its transport/ merges with the transport's.
for entry in "$WEB/dist/app/"*; do
  name="$(basename "$entry")"
  if [ -e "$SITE/$name" ] && [ "$name" != transport ]; then
    echo "the app's $name collides with the site's" >&2
    exit 1
  fi
done
cp -r "$WEB/dist/app/." "$SITE/"

# Protobuf code from Signal's own generator (same version as upstream Desktop).
# The generated module imports its small runtime by package name; ship the
# runtime next to it and point the import there.
"$WEB/node_modules/.bin/protopiler" \
  "$WEB/protos/SubProtocol.proto" "$REPO/protos/DeviceMessages.proto" \
  --output "$SITE/lib/protos.mjs"
sed -i "s#from '@indutny/protopiler';#from './protopiler.mjs';#" "$SITE/lib/protos.mjs"
grep -q "from './protopiler.mjs';" "$SITE/lib/protos.mjs" || {
  echo "protopiler output changed: runtime import not found" >&2
  exit 1
}
cp "$WEB/node_modules/@indutny/protopiler/dist/index.mjs" "$SITE/lib/protopiler.mjs"

# Tor directory snapshot: fetched fresh at build time, never committed.
if [ -z "$TOR_DIR" ]; then
  TOR_DIR="$WEB/dist/tor-directory"
  rm -rf "$TOR_DIR"
  bash "$WEB/transport/webtor-rs/scripts/fetch-consensus.sh" "$TOR_DIR"
fi
for name in consensus certs microdescriptors; do
  if [ ! -f "$TOR_DIR/$name.txt.br" ]; then
    echo "Tor directory snapshot incomplete: $TOR_DIR/$name.txt.br missing" >&2
    exit 1
  fi
  cp "$TOR_DIR/$name.txt.br" "$SITE/transport/tor/"
done
# The same verification the client runs (signatures, authority certificates,
# lifetime, microdescriptor digests), with the site's own WebAssembly.
node "$WEB/transport/verify-directory.mjs" "$SITE/transport/tor"

# Subresource Integrity for the check pages (the app's index.html gets it
# in renderer/build.mjs).
node "$WEB/scripts/sri.mjs" "$SITE/test/index.html" "$SITE/libsignal/index.html"

# What the site was built from, and the digest of every file except the Tor
# directory snapshot (data that changes daily): scripts/verify-site.sh
# rebuilds a commit and compares with these.
{
  echo "receiver $(git -C "$REPO" rev-parse HEAD)"
  # The submodule commits recorded in that commit (CI does not check out libsignal).
  echo "webtor-rs $(git -C "$REPO" rev-parse HEAD:web/transport/webtor-rs)"
  echo "libsignal $(git -C "$REPO" rev-parse HEAD:web/libsignal/libsignal)"
  if [ -n "$(git -C "$REPO" status --porcelain --untracked-files=no)" ]; then
    echo "built with uncommitted changes"
  fi
  echo "source https://github.com/insertokname/receiver"
} > "$SITE/SOURCE"
(
  cd "$SITE"
  find . -type f ! -path './transport/tor/*' -printf '%P\n' | LC_ALL=C sort \
    | xargs -d '\n' sha256sum -- > "$WEB/dist/SHA256SUMS"
)
mv "$WEB/dist/SHA256SUMS" "$SITE/SHA256SUMS"
echo "SHA256SUMS: $(wc -l < "$SITE/SHA256SUMS") files, $(sha256sum "$SITE/SHA256SUMS" | cut -c1-16)"

du -sh "$SITE"
find "$SITE" -maxdepth 2 -not -path "$SITE/chunks/*" -not -path "$SITE/fonts/*" -not -path "$SITE/images/*" \
  -not -path "$SITE/sounds/*" -not -path "$SITE/locales/*" -not -path "$SITE/stylesheets/*" | sort
echo "files: $(find "$SITE" -type f | wc -l)"
