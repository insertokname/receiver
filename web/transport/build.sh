#
# Builds the Tor transport into web/transport/dist/ (git-ignored):
#   pkg/          webtor-rs compiled to WASM (wasm-pack --target web --release)
#   signal-ca.js  Signal's CA, taken from config/default.json certificateAuthority
#   wasm-integrity.js  SRI digests of the WebAssembly and the timer worker, checked when they are loaded
#   index.js      the connection policy (src/index.js, types in src/index.d.ts)
#   ranged.js     large downloads in parallel byte ranges (src/ranged.js)
#   timers.js, timer-worker.js  timers kept on time in a hidden page (src/timers.js)
#
# Needs: the Rust toolchain pinned in webtor-rs/rust-toolchain.toml with the
# wasm32-unknown-unknown target, wasm-pack, wasm-opt (binaryen; wasm-pack
# would otherwise download one of its own), clang + llvm-ar that can target
# wasm32 (for ring; override with CC_wasm32_unknown_unknown /
# AR_wasm32_unknown_unknown), node.
#
# Usage: transport/build.sh [--test-relay]
#   --test-relay builds the end-to-end test variant into dist-e2e/ instead:
#   the same code plus webtor's `test-relay` feature (TLS carried by a
#   WebSocket to a local relay in front of a mock server, see web/e2e/).
#   Production builds never enable it.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
OUT="$HERE/dist"
FEATURES=()

while [ $# -gt 0 ]; do
  case "$1" in
    --test-relay) OUT="$HERE/dist-e2e"; FEATURES=(--features test-relay); shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

if ! command -v wasm-opt > /dev/null; then
  echo "wasm-opt not found: install binaryen (the version in .github/workflows/web-pages.yml)" >&2
  exit 1
fi

if [ ! -f "$HERE/webtor-rs/Cargo.toml" ]; then
  echo "webtor-rs submodule missing: git submodule update --init web/transport/webtor-rs" >&2
  exit 1
fi

rm -rf "$OUT"
mkdir -p "$OUT"

# Reproducible output: no build-machine paths in the module (panic messages
# carry source paths). Dependencies' sources map to /cargo, the standard
# library's to /rustc/<commit> (as in the prebuilt std), the workspace to
# /webtor-rs.
(
  cd "$HERE/webtor-rs"
  sysroot="$(rustc --print sysroot)"
  commit="$(rustc -vV | sed -n 's/^commit-hash: //p')"
  export RUSTFLAGS="--remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=/cargo --remap-path-prefix=$sysroot/lib/rustlib/src/rust=/rustc/$commit --remap-path-prefix=$HERE/webtor-rs=/webtor-rs"
  cd webtor-wasm
  wasm-pack build --target web --release --no-pack --out-dir "$OUT/pkg" -- "${FEATURES[@]}"
)
rm -f "$OUT/pkg/.gitignore"

# shellcheck disable=SC2016 # JavaScript, not shell
node -e '
  const fs = require("node:fs");
  const pem = JSON.parse(fs.readFileSync(process.argv[1], "utf8")).certificateAuthority;
  const certs = (pem.match(/-----BEGIN CERTIFICATE-----/g) ?? []).length;
  if (certs !== 1 || !pem.trim().endsWith("-----END CERTIFICATE-----")) {
    throw new Error(`expected exactly one PEM certificate in certificateAuthority, found ${certs}`);
  }
  fs.writeFileSync(process.argv[2],
    "// Generated from config/default.json certificateAuthority by web/transport/build.sh.\n" +
    "export default " + JSON.stringify(pem) + ";\n");
' "$REPO/config/default.json" "$OUT/signal-ca.js"

cp "$HERE/src/index.js" "$HERE/src/index.d.ts" "$HERE/src/ranged.js" "$HERE/src/timers.js" "$HERE/src/timer-worker.js" "$OUT/"

# SRI digests of the module and the timer worker, checked when index.js loads them.
sri() { printf 'sha384-%s' "$(openssl dgst -sha384 -binary "$1" | base64 -w0)"; }
printf '// Generated by web/transport/build.sh: SRI digests of pkg/webtor_wasm_bg.wasm and timer-worker.js.\nexport default "%s";\nexport const TIMER_WORKER_INTEGRITY = "%s";\n' \
  "$(sri "$OUT/pkg/webtor_wasm_bg.wasm")" "$(sri "$OUT/timer-worker.js")" > "$OUT/wasm-integrity.js"

ls -l "$OUT" "$OUT/pkg"
